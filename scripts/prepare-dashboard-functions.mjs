import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Generated copies make Dashboard editor deployment possible without local imports.
// Canonical, tested implementations remain under supabase/functions.
const root = new URL('../', import.meta.url);
const shared = await readFile(new URL('supabase/functions/_shared/payment-security.js', root), 'utf8');
const directory = new URL('supabase/dashboard-functions/', root);
await mkdir(directory, { recursive: true });
for (const name of ['payments', 'payment-webhook']) {
  const source = await readFile(new URL(`supabase/functions/${name}/index.ts`, root), 'utf8');
  const body = source.replace(/^import .* from '\.\.\/_shared\/payment-security\.js';\r?\n/m, shared + '\n');
  if (body === source) throw new Error(`Shared import was not replaced for ${name}.`);
  await writeFile(new URL(`${name}.ts`, directory), '// Generated by scripts/prepare-dashboard-functions.mjs.\n' + body);
  console.log(fileURLToPath(new URL(`${name}.ts`, directory)));
}

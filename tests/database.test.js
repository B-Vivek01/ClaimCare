import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { PGlite } from '@electric-sql/pglite';
const alice = '00000000-0000-4000-8000-000000000001';
const bob = '00000000-0000-4000-8000-000000000002';
const ops = '00000000-0000-4000-8000-000000000003';
test('database enforces ownership, revisions, staff access, and profile roles', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth; create schema storage;
      create table auth.users(id uuid primary key, email text, raw_user_meta_data jsonb,phone text,email_confirmed_at timestamptz,phone_confirmed_at timestamptz);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
      grant usage on schema auth, public, storage to authenticated; grant execute on function auth.uid() to authenticated;
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
      create table storage.objects(id text,name text,bucket_id text); alter table storage.objects enable row level security;
      create function storage.foldername(text) returns text[] language sql as $$ select string_to_array($1, '/') $$;`);
    await db.exec(await readFile(new URL('../supabase/migrations/001_core.sql', import.meta.url), 'utf8'));
    await db.exec(await readFile(new URL('../supabase/migrations/002_payments.sql', import.meta.url), 'utf8'));
    await db.exec(await readFile(new URL('../supabase/migrations/003_events.sql', import.meta.url), 'utf8'));
    await db.exec(await readFile(new URL('../supabase/migrations/004_support.sql', import.meta.url), 'utf8'));
    await db.exec(await readFile(new URL('../supabase/migrations/005_identity.sql', import.meta.url), 'utf8'));
    await db.exec(await readFile(new URL('../supabase/migrations/006_validation.sql', import.meta.url), 'utf8'));
    await db.exec(await readFile(new URL('../supabase/migrations/007_profile_guards.sql', import.meta.url), 'utf8'));
    await db.exec(await readFile(new URL('../supabase/migrations/008_staff_reviews.sql', import.meta.url), 'utf8'));
    await db.exec(await readFile(new URL('../supabase/migrations/009_claim_progress.sql', import.meta.url), 'utf8'));
    await db.exec(await readFile(new URL('../supabase/migrations/010_document_notifications.sql', import.meta.url), 'utf8'));
    await db.query('insert into auth.users(id,email,raw_user_meta_data) values ($1,$2,$3),($4,$5,$6),($7,$8,$9)', [alice, 'alice@example.test', {name:'Alice'}, bob, 'bob@example.test', {name:'Bob'}, ops, 'ops@example.test', {name:'Ops'}]);
    await db.query(`update profiles set data = data || '{"role":"operations"}' where id=$1`, [ops]);
    const as = async uid => { await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[uid]); await db.exec('set role authenticated'); };
    const mutate = (name, changes) => db.query('select mutate_records($1,$2)', [name, changes]);
    await as(alice);
    assert.equal((await db.query('select * from profiles')).rows.length, 1);
    await assert.rejects(db.query('select update_profile($1,$2)', [alice, {role:'admin'}]), /not permitted/);
    await db.query('select update_profile($1,$2)', [alice, {name:'Alice Updated'}]);
    const claim = { id:'CLM-one', ownerId:alice, status:'Draft', assignedSpecialist:null, internalNotes:[], priority:'Medium' };
    await mutate('claims', [{action:'write', id:claim.id, expected_revision:0, data:claim}]);
    assert.equal((await db.query('select * from records')).rows.length, 1);
    await assert.rejects(mutate('claims', [{action:'write', id:claim.id, expected_revision:0, data:claim}]), /another session/);
    await assert.rejects(mutate('claims', [{action:'write', id:claim.id, expected_revision:1, data:{...claim,status:'Approved'}}]), /requires staff/);
    await assert.rejects(mutate('claims', [{action:'write', id:claim.id, expected_revision:1, data:{...claim,priority:'High'}}]), /staff/);
    await assert.rejects(mutate('claims', [{action:'write',id:claim.id,expected_revision:1,data:{...claim,status:'Submitted'}}]), /required claim/);
    await as(bob);
    assert.equal((await db.query('select * from records')).rows.length, 0);
    await assert.rejects(mutate('claims', [{action:'write',id:claim.id,expected_revision:1,data:{...claim,ownerId:bob}}]), /Access denied/);
    await as(ops);
    assert.equal((await db.query('select * from records')).rows.length, 1);
    await mutate('claims', [{action:'write',id:claim.id,expected_revision:1,data:{...claim,status:'In Review'}}]);
    await assert.rejects(mutate('claims', [{action:'write',id:claim.id,expected_revision:2,data:{...claim,status:'Closed'}}]), /checklist/);
    assert.equal((await db.query("select * from audit_events where module='claims'")).rows.length,2);
    const note = {id:'note-1',ownerId:ops,claimId:claim.id,note:'Staff only'};
    await mutate('claim_internal', [{action:'write',id:note.id,expected_revision:0,data:note}]);
    await as(alice);
    assert.equal((await db.query("select * from records where collection='notifications'")).rows.length,1);
    await assert.rejects(mutate('claims', [{action:'write',id:claim.id,expected_revision:2,data:{...claim,status:'In Review',incidentDescription:'Changed'}}]), /staff correction/);
    assert.equal((await db.query("select * from records where collection='claim_internal'")).rows.length, 0);
    await assert.rejects(mutate('claims', [{action:'delete',id:claim.id,expected_revision:2}]), /Archive/);
    await assert.rejects(mutate('invoices',[{action:'write',id:'INV-one',expected_revision:0,data:{id:'INV-one',ownerId:alice,total:118,status:'Pending'}}]), /Staff/);
    await as(ops);
    const invoice = {id:'INV-one',ownerId:alice,customer:'Alice',amount:100,tax:18,total:118,status:'Pending'};
    await mutate('invoices',[{action:'write',id:invoice.id,expected_revision:0,data:invoice}]);
    await db.exec('reset role');
    await db.query("insert into payment_orders(id,invoice_id,owner_id,amount) values('order_test','INV-one',$1,11800)",[alice]);
    await as(ops);
    await assert.rejects(mutate('invoices',[{action:'write',id:invoice.id,expected_revision:1,data:{...invoice,total:1}}]), /locked/);
    await as(alice);
    await assert.rejects(db.query("select finalize_payment('order_test','pay_test','upi')"), /permission denied/);
    await assert.rejects(mutate('payments',[]), /Unsupported/);
    await db.exec('reset role; set role service_role');
    await db.query("select finalize_payment('order_test','pay_test','upi')");
    await db.query("select finalize_payment('order_test','pay_test','upi')");
    await as(alice);
    assert.equal((await db.query("select * from records where collection='payments'")).rows.length,1);
    assert.equal((await db.query("select data->>'status' as status from records where collection='invoices'")).rows[0].status,'Paid');
    await as(bob);
    assert.equal((await db.query("select * from records where collection='payments'")).rows.length,0);
    await assert.rejects(mutate('refunds',[{action:'write',id:'REF-one',expected_revision:0,data:{id:'REF-one',ownerId:bob,paymentId:'pay_test',amount:118,status:'Pending'}}]), /verified payment/);
    await db.exec('reset role');
    await db.query(`update profiles set data = data || '{"role":"admin"}' where id=$1`,[ops]);
    await as(ops);
    await assert.rejects(db.query('select update_profile($1,$2)',[ops,{disabled:true}]), /own access/);
    await assert.rejects(db.query('select update_profile($1,$2)',[bob,{role:'invalid'}]), /Invalid account role/);
    await assert.rejects(db.query('select update_profile($1,$2)',[ops,{role:null}]), /Invalid account role/);
    await as(alice);
    const contact={name:'Alice',email:'support@example.test',subject:'Help with a claim',message:'Please help me with this claim.'};
    const ticket=(await db.query('select submit_support_request($1) as id',[contact])).rows[0].id;
    assert.equal((await db.query('select * from support_requests')).rows.length,0);
    await assert.rejects(db.query('select update_support_request($1,$2,$3,$4)',[ticket,'Closed','Resolved',1]),/Staff/);
    await assert.rejects(db.query('select request_identity_review()'),/Upload an identity/);
    const identity={id:'DOC-identity',ownerId:alice,category:'Identity',storagePath:`${alice}/identity.pdf`,fileType:'application/pdf',reviewStatus:'Pending',scanStatus:'Not scanned'};
    await mutate('documents',[{action:'write',id:identity.id,expected_revision:0,data:identity}]);
    await db.query('select request_identity_review()');
    await assert.rejects(db.query('select review_identity($1,$2,$3,$4,$5)',[alice,identity.id,1,'verified','']),/Staff/);
    await db.exec('reset role');
    await db.query('insert into storage.objects(id,name,bucket_id) values($1,$2,$3)',['object-identity',identity.storagePath,'documents']);
    await as(ops);
    await db.query('select update_support_request($1,$2,$3,$4)',[ticket,'Closed','Resolved',1]);
    await assert.rejects(db.query('select update_support_request($1,$2,$3,$4)',[ticket,'Open','Stale note',1]),/changed/);
    await assert.rejects(db.query('select review_identity($1,$2,$3,$4,$5)',[alice,identity.id,0,'verified','']),/Document changed/);
    await assert.rejects(db.query('select review_identity($1,$2,$3,$4,$5)',[alice,identity.id,1,'rejected','']),/rejection reason/);
    await assert.rejects(db.query('select review_identity($1,$2,$3,$4,$5)',[bob,identity.id,1,'verified','']),/not pending/);
    await db.query('select review_identity($1,$2,$3,$4,$5)',[alice,identity.id,1,'verified','Reviewed test document']);
    await as(alice);
    assert.equal((await db.query("select data->>'identityStatus' as status from profiles where id=$1",[alice])).rows[0].status,'verified');
    assert.equal((await db.query("select data->>'reviewStatus' as status from records where collection='documents' and id=$1",[identity.id])).rows[0].status,'Accepted');
    const reviewNotices = await db.query("select owner_id,data from records where collection='notifications' and data->>'target'=$1", ['/documents/' + identity.id]);
    assert.equal(reviewNotices.rows.length, 1);
    assert.equal(reviewNotices.rows[0].data.status, 'Unread');
    assert.match(reviewNotices.rows[0].data.message, /Accepted/);
    await as(ops);
    const closed={...claim,status:'Closed',closure:{checklistCompleted:true}};
    await mutate('claims',[{action:'write',id:claim.id,expected_revision:2,data:closed}]);
    await assert.rejects(mutate('claims',[{action:'write',id:claim.id,expected_revision:3,data:{...closed,status:'Under Review'}}]),/reopening/);
    assert.equal((await db.query("select data->>'expectedNextStep' as next from records where collection='claims' and id=$1",[claim.id])).rows[0].next,'Claim review is complete.');
    await as(alice);
    await mutate('claims',[{action:'write',id:claim.id,expected_revision:3,data:{...closed,status:'Reopen Requested',archived:false}}]);
    await db.exec('reset role');
    await db.query(`update profiles set data = data || '{"disabled":true}' where id=$1`,[alice]);
    await as(alice);
    assert.equal((await db.query('select * from records')).rows.length, 0);
    await assert.rejects(mutate('policies',[]), /active account/);
  } finally { await db.close(); }
});
